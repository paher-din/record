package com.paherdin.record.core.data

import com.paherdin.record.model.TransactionType
import org.junit.Assert.assertEquals
import org.junit.Assert.assertThrows
import org.junit.Assert.fail
import org.junit.Test
import java.math.BigInteger
import java.util.Random

/**
 * Criterion 4: balance reproducibility across arbitrary P2-valid history
 * (testing strategy "Balance drift across arbitrary history"). Fixed seeds
 * only — every run is reproducible; the seed is printed so it can be recorded
 * in `verification.md`. The generator produces P2-valid histories (spec 4.1);
 * after every step, a `BigInteger` oracle equals the effective-entry sum for
 * each account and every transfer keeps exact zero sum. Invalid candidates are
 * generated by mutation and each must be rejected with its precise violation.
 */
class BalanceReproducibilityPropertyTest {

    private val validator = FinanceMatrixValidator()

    /** Fixed account pool: two CNY accounts and two USD accounts so same-currency transfers exist. */
    private val accounts = mapOf(
        "acct-a" to "CNY",
        "acct-b" to "CNY",
        "acct-c" to "USD",
        "acct-d" to "USD",
    )

    private val transferPairs = listOf("acct-a" to "acct-b", "acct-c" to "acct-d")

    private data class Tx(
        val type: TransactionType,
        val entries: List<Pair<String, Long>>, // (accountId, amountMinor)
        var deleted: Boolean = false,
    )

    private val currency = { accountId: String -> accounts.getValue(accountId) }

    private fun runSeed(seed: Long, steps: Int) {
        val random = Random(seed)
        // Mask the sign bit so magnitudes are always non-negative (never abs(Long.MIN_VALUE)).
        val magnitude = { bound: Long -> (random.nextLong() and Long.MAX_VALUE) % bound + 1L }
        val txs = mutableListOf<Tx>()
        val opTrace = StringBuilder()
        val check = { context: String ->
            // BigInteger oracle: balance = sum of effective (non-deleted) entries per account.
            val expected = mutableMapOf<String, BigInteger>()
            txs.filter { !it.deleted }.forEach { tx ->
                tx.entries.forEach { (accountId, amount) ->
                    expected.merge(accountId, amount.toBigInteger(), BigInteger::add)
                }
            }
            accounts.keys.forEach { accountId ->
                assertEquals(
                    "balance drift for $accountId at $context",
                    expected[accountId] ?: BigInteger.ZERO,
                    oracleBalance(accountId, txs),
                )
            }
            // Every transfer is exactly zero-sum in the model.
            txs.filter { it.type == TransactionType.TRANSFER }.forEach { tx ->
                val sum = tx.entries.fold(BigInteger.ZERO) { acc, (_, amount) -> acc.add(amount.toBigInteger()) }
                assertEquals("transfer zero-sum drift at $context", BigInteger.ZERO, sum)
            }
        }

        fun toEntries(entries: List<Pair<String, Long>>, i: Int): List<NewAccountEntry> =
            entries.mapIndexed { index, (accountId, amount) ->
                NewAccountEntry(id = "op$i-e$index", accountId = accountId, amountMinor = amount)
            }

        repeat(steps) { i ->
            when (random.nextInt(5)) {
                0 -> { // OPENING_BALANCE on a random account; zero permitted occasionally.
                    val accountId = accounts.keys.toList()[random.nextInt(accounts.size)]
                    val amount = if (random.nextInt(10) == 0) 0L
                    else random.nextLong() % 1_000_000L
                    val entries = listOf(accountId to amount)
                    val aggregate = toEntries(entries, i)
                    assertValid(TransactionType.OPENING_BALANCE, aggregate)
                    txs += Tx(TransactionType.OPENING_BALANCE, entries)
                }
                1 -> { // INCOME: exactly one positive entry.
                    val accountId = accounts.keys.toList()[random.nextInt(accounts.size)]
                    val amount = magnitude(1_000_000L)
                    val entries = listOf(accountId to amount)
                    assertValid(TransactionType.INCOME, toEntries(entries, i))
                    txs += Tx(TransactionType.INCOME, entries)
                }
                2 -> { // EXPENSE: exactly one negative entry.
                    val accountId = accounts.keys.toList()[random.nextInt(accounts.size)]
                    val amount = -magnitude(1_000_000L)
                    val entries = listOf(accountId to amount)
                    assertValid(TransactionType.EXPENSE, toEntries(entries, i))
                    txs += Tx(TransactionType.EXPENSE, entries)
                }
                3 -> { // TRANSFER: two distinct same-currency accounts, zero sum.
                    val (src, dst) = transferPairs[random.nextInt(transferPairs.size)]
                    val magnitude = magnitude(1_000_000L)
                    val entries = listOf(src to -magnitude, dst to magnitude)
                    assertValid(TransactionType.TRANSFER, toEntries(entries, i))
                    txs += Tx(TransactionType.TRANSFER, entries)
                }
                4 -> { // Pure-model soft-delete transition: mark an existing transaction deleted.
                    val candidate = txs.filter { !it.deleted }
                    if (candidate.isNotEmpty()) candidate[random.nextInt(candidate.size)].deleted = true
                }
            }
            opTrace.append("op$i: ${txs.lastOrNull()?.type}\n")
            check("step $i")
        }
        println("seed=$seed steps=$steps balance-reproducibility OK")
    }

    private fun oracleBalance(accountId: String, txs: List<Tx>): BigInteger =
        txs.filter { !it.deleted }
            .flatMap { it.entries }
            .filter { (id, _) -> id == accountId }
            .fold(BigInteger.ZERO) { acc, (_, amount) -> acc.add(amount.toBigInteger()) }

    private fun assertValid(type: TransactionType, entries: List<NewAccountEntry>) {
        validator.validate(type, entries, accounts)
    }

    private fun assertViolation(expected: FinanceViolation, type: TransactionType, entries: List<NewAccountEntry>) {
        val e = assertThrows(FinanceViolationException::class.java) {
            validator.validate(type, entries, accounts)
        }
        assertEquals(expected, e.violation)
    }

    private fun entry(accountId: String, amountMinor: Long) =
        NewAccountEntry(id = "m-$accountId-$amountMinor", accountId = accountId, amountMinor = amountMinor)

    @Test
    fun arbitraryHistoryKeepsBalancesReproducible() {
        runSeed(0xC0FFEE, 400)
        runSeed(0xBEEF, 400)
        runSeed(2_026_08_05, 400)
    }

    // ---- invalid candidates by mutation ----

    @Test
    fun mutatedCandidatesAreRejectedWithPreciseViolations() {
        assertViolation(FinanceViolation.WRONG_SIGN, TransactionType.INCOME, listOf(entry("acct-a", -5L)))
        assertViolation(FinanceViolation.ZERO_AMOUNT, TransactionType.INCOME, listOf(entry("acct-a", 0L)))
        assertViolation(FinanceViolation.ENTRY_CARDINALITY, TransactionType.INCOME, emptyList())
        assertViolation(FinanceViolation.WRONG_SIGN, TransactionType.EXPENSE, listOf(entry("acct-a", 5L)))
        assertViolation(FinanceViolation.ENTRY_CARDINALITY, TransactionType.TRANSFER, listOf(entry("acct-a", -5L)))
        assertViolation(
            FinanceViolation.TRANSFER_SAME_ACCOUNT, TransactionType.TRANSFER,
            listOf(entry("acct-a", -5L), entry("acct-a", 5L)),
        )
        assertViolation(
            FinanceViolation.TRANSFER_CURRENCY_MISMATCH, TransactionType.TRANSFER,
            listOf(entry("acct-a", -5L), entry("acct-c", 5L)),
        )
        assertViolation(
            FinanceViolation.TRANSFER_NOT_ZERO_SUM, TransactionType.TRANSFER,
            listOf(entry("acct-a", -4L), entry("acct-b", 5L)),
        )
        assertViolation(
            FinanceViolation.ZERO_AMOUNT, TransactionType.TRANSFER,
            listOf(entry("acct-a", 0L), entry("acct-b", 5L)),
        )
    }
}
